    /// <summary>
    /// Unit tests for the stream comparer / known-diff consumption (no device session).
    /// </summary>
    [Collection(ReplayParityCollection.Name)]
    public class StreamComparerTests
    {
        public StreamComparerTests()
        {
            CultureInfo.CurrentCulture = CultureInfo.InvariantCulture;
            CultureInfo.CurrentUICulture = CultureInfo.InvariantCulture;
        }

        [Fact]
        public void Compare_IdenticalStreams_Pass()
        {
            byte[] p = { 1, 2, 3 };
            var a = new[]
            {
                new WireAttempt(0, 0, 0, Chan.Col01, p, true),
                new WireAttempt(1, 0, 16, Chan.Col03, p, true),
            };
            var r = StreamComparer.Compare(a, a);
            Assert.True(r.Passed, r.Failure);
        }

        [Fact]
        public void Compare_UnknownDiff_Fails()
        {
            var v9 = new[] { new WireAttempt(0, 0, 0, Chan.Col01, new byte[] { 1 }, true) };
            var v2 = new[] { new WireAttempt(0, 0, 0, Chan.Col01, new byte[] { 2 }, true) };
            var r = StreamComparer.Compare(v9, v2);
            Assert.False(r.Passed);
            Assert.Contains("mismatch", r.Failure!, StringComparison.OrdinalIgnoreCase);
        }

        [Fact]
        public void Compare_NamedKnownDiff_Consumes()
        {
            var v9 = new[] { new WireAttempt(5, 0, 80, Chan.Col03, new byte[] { 0xAA }, true) };
            var v2 = new[] { new WireAttempt(5, 0, 80, Chan.Col03, new byte[] { 0xBB }, true) };
            var diffs = new[]
            {
                new KnownDiff("suffix-blink", 5, Chan.Col03, new byte[] { 0xAA }, new byte[] { 0xBB }),
            };
            var r = StreamComparer.Compare(v9, v2, diffs);
            Assert.True(r.Passed, r.Failure);
        }

        [Fact]
        public void Compare_UnconsumedKnownDiff_Fails()
        {
            var a = new[] { new WireAttempt(0, 0, 0, Chan.Col01, new byte[] { 1 }, true) };
            var diffs = new[]
            {
                new KnownDiff("never-happened", 9, Chan.Col03, new byte[] { 1 }, null),
            };
            var r = StreamComparer.Compare(a, a, diffs);
            Assert.False(r.Passed);
            Assert.Contains("Unconsumed", r.Failure!, StringComparison.Ordinal);
        }

        /// <summary>
        /// Codex probe: named class handlers must not discard an unnamed AA/BB tail
        /// (no prefix-retention / LCP keep / tail truncate).
        /// </summary>
        [Fact]
        public void Compare_AdversarialUnnamedTail_Fails()
        {
            // Shared prefix that would satisfy a class pin (Speed col01), then unnamed tail.
            byte[] speed = ReplayKnownDiffs.Speed142Col01;
            var v9 = new[]
            {
                new WireAttempt(0, 0, 0, Chan.Col01, speed, true),
                new WireAttempt(1, 0, 16, Chan.Col03, new byte[] { 0xAA }, true),
            };
            var v2 = new[]
            {
                new WireAttempt(0, 0, 0, Chan.Col01, speed, true),
                new WireAttempt(1, 0, 16, Chan.Col03, new byte[] { 0xBB }, true),
            };

            // Segment-screen class substitutes the pinned SetPage only; residual AA/BB
            // must fail (would have Passed=True under LCP discard / tail truncate).
            var setPage = ReplayKnownDiffs.SetPageLegacyPbme;
            var v9s = new[]
            {
                new WireAttempt(0, 0, 0, Chan.Col03, setPage, true),
                new WireAttempt(1, 0, 16, Chan.Col03, new byte[] { 0xAA }, true),
            };
            var v2s = new[]
            {
                new WireAttempt(0, 0, 0, Chan.Col03, setPage, true),
                new WireAttempt(1, 0, 16, Chan.Col03, new byte[] { 0xBB }, true),
            };
            var r = StreamComparer.Compare(v9s, v2s, new[]
            {
                ReplayKnownDiffs.SegmentScreenSetPageOrdering,
            });
            Assert.False(r.Passed);
            Assert.Contains("mismatch", r.Failure!, StringComparison.OrdinalIgnoreCase);

            // Blank-idle one-sided class: pin removes blank only — AA/BB tail still fails.
            byte[] blank = { 0x01, 0xF8, 0x09, 0x01, 0x50, 0x00, 0x00, 0x00 };
            var v9b = new[]
            {
                new WireAttempt(0, 0, 0, Chan.Col01, speed, true),
                new WireAttempt(1, 0, 16, Chan.Col03, new byte[] { 0xAA }, true),
            };
            var v2b = new[]
            {
                new WireAttempt(0, 0, 0, Chan.Col01, speed, true),
                new WireAttempt(0, 1, 0, Chan.Col01, blank, true),
                new WireAttempt(1, 0, 16, Chan.Col03, new byte[] { 0xBB }, true),
            };
            var r2 = StreamComparer.Compare(v9b, v2b, new[]
            {
                ReplayKnownDiffs.BlankCompileFirmwareIdle,
            });
            Assert.False(r2.Passed);
            Assert.Contains("mismatch", r2.Failure!, StringComparison.OrdinalIgnoreCase);
        }
