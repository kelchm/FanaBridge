        [Fact]
        public void Normalizer_CollapsesDeclinedSetPageRuns()
        {
            // FF 05 04 03 01 — SetPage device 3 page 1
            byte[] page = { 0xFF, 0x05, 0x04, 0x03, 0x01 };
            byte[] other = { 0xFF, 0x05, 0x02, 0x01 }; // EnableItm-shaped

            var raw = new List<WireAttempt>
            {
                new WireAttempt(1, 0, 16, Chan.Col03, page, accepted: false),
                new WireAttempt(2, 0, 32, Chan.Col03, page, accepted: false),
                new WireAttempt(3, 0, 48, Chan.Col03, page, accepted: true),
                new WireAttempt(4, 0, 64, Chan.Col03, other, accepted: true),
            };

            var n = PageSetRetryNormalizer.Normalize(raw);
            Assert.Equal(2, n.Count);
            Assert.True(n[0].Accepted);
            Assert.Equal(1, n[0].FrameIndex); // first frame of run retained
            Assert.True(WireAttempt.PayloadBytesEqual(other, n[1].Payload));
        }

        /// <summary>
        /// H5: on lifecycle recovery the v2 reconnect burst must command SetPage before
        /// the first col01 face write (v9 cold-entry ordering). Hosted-only page-policy
        /// decline is unchanged in steady state; only the recovery burst ordering aligns.
        /// </summary>
        [Fact]
        public void LifecycleRecovery_V2_SetPagePrecedesFirstCol01FaceInReconnectBurst()
        {
            var cell = ReplayMatrix.ById(
                "e8-pbme-segment-screen-greater-than-for-duration-in-game-known-page-none-lifecycle-recovery");
            Assert.True(cell.IsRepresentable);
            Assert.Equal(ReplayWire.LifecycleRecovery, cell.Wire);

            var (_, v2) = ReplayHarness.RunPair(cell);
            // Second DisplayReset (FF 05 05 01) opens the reconnect bring-up burst.
            int reconnect = -1;
            int resets = 0;
            for (int i = 0; i < v2.Count; i++)
            {
                if (v2[i].Channel != Chan.Col03 || v2[i].Payload.Length < 3)
                    continue;
                if (v2[i].Payload[0] == 0xFF && v2[i].Payload[1] == 0x05
                    && v2[i].Payload[2] == 0x05)
                {
                    resets++;
                    if (resets == 2)
                    {
                        reconnect = i;
                        break;
                    }
                }
            }
            Assert.True(reconnect >= 0, "v2 stream missing reconnect DisplayReset");

            int setPage = -1;
            int col01 = -1;
            for (int i = reconnect; i < v2.Count; i++)
            {
                if (setPage < 0 && PageSetRetryNormalizer.IsSetPage(v2[i].Payload))
                    setPage = i;
                if (col01 < 0 && v2[i].Channel == Chan.Col01)
                    col01 = i;
                if (setPage >= 0 && col01 >= 0)
                    break;
            }

            Assert.True(setPage >= 0, "v2 reconnect burst missing SetPage");
            Assert.True(col01 >= 0, "v2 reconnect burst missing col01 face write");
            Assert.True(setPage < col01,
                "H5: recovery SetPage must precede first col01 face paint (setPage@ "
                + setPage + " col01@ " + col01 + ")");
            Assert.Equal(v2[reconnect].FrameIndex, v2[setPage].FrameIndex);
        }

